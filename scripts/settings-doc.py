#!/usr/bin/env python3
"""Write the settings reference in docs/configuration.md from src/agentgov/config.py.

Every field of ``Settings`` is an ``AGENTGOV_<NAME>`` environment variable. The comment
above a field, or above a run of fields with no blank line between them, says what they
do; ``# --- Title ---`` comments start a section. The reference sits between two markers
in docs/configuration.md, and the rest of that page is written by hand.

  scripts/settings-doc.py           rewrite the reference
  scripts/settings-doc.py --check   fail if it is out of date, or a setting has no comment
"""

from __future__ import annotations

import ast
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "src" / "agentgov" / "config.py"
DOC = ROOT / "docs" / "configuration.md"
BEGIN = "<!-- BEGIN settings reference: generated by scripts/settings-doc.py -->"
END = "<!-- END settings reference -->"
SECTION = re.compile(r"^#\s*---\s*(.+?)\s*-*$")
# Settings whose values are credentials: keep them in a secret store.
SECRET = re.compile(r"(token|secret|password|api_key)$|^database_url$")


@dataclass
class Section:
    title: str
    intro: str = ""
    groups: list[Group] = field(default_factory=list)


@dataclass
class Group:
    """Settings that one comment describes."""

    what: str
    names: list[str] = field(default_factory=list)
    defaults: list[str] = field(default_factory=list)


def _default(node: ast.expr | None) -> str:
    if node is None:
        return "—"
    try:
        value = ast.literal_eval(node)
    except ValueError:
        return f"`{ast.unparse(node)}`"
    if value is None:
        return "—"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if value == "":
        return "empty"
    return f"`{value}`"


def sections() -> list[Section]:
    """The sections of settings, in the order of config.py."""
    source = CONFIG.read_text()
    lines = source.splitlines()
    settings = next(
        n for n in ast.parse(source).body if isinstance(n, ast.ClassDef) and n.name == "Settings"
    )
    fields = {
        n.lineno: n
        for n in settings.body
        if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)
    }
    end = max(n.end_lineno or n.lineno for n in fields.values())
    out = [Section("Settings")]
    comment: list[str] = []
    group: Group | None = None
    # A comment right under a section's title, before a blank line, introduces it.
    intro = False
    number = settings.lineno + 1
    while number <= end:
        text = lines[number - 1].strip()
        node = fields.get(number)
        if node is not None:
            name = node.target.id  # type: ignore[union-attr]
            if comment or group is None:
                group = Group(" ".join(comment))
                out[-1].groups.append(group)
                comment = []
            intro = False
            label = f"`AGENTGOV_{name.upper()}`"
            group.names.append(f"{label} (secret)" if SECRET.search(name) else label)
            group.defaults.append(_default(node.value))
            number = (node.end_lineno or number) + 1
            continue
        title = SECTION.match(text)
        if title:
            out.append(Section(title[1]))
            comment, group, intro = [], None, True
        elif text.startswith("#"):
            comment.append(text.lstrip("#").strip())
        elif not text:
            group = None
            if intro and comment:
                out[-1].intro, comment = " ".join(comment), []
            intro = False
        number += 1
    return [section for section in out if section.groups]


def _text(what: str, names: set[str]) -> str:
    """A comment as the reference shows it: settings by their variables, values and
    addresses as code, and links to the pages it names."""

    def variable(match: re.Match[str]) -> str:
        name = match[0]
        return f"`AGENTGOV_{name.upper()}`" if name in names else name

    what = re.sub(r'"([^"\s][^"]*)"', r"`\1`", what)
    what = re.sub(r"(?<![`/])\bhttps?://[^\s`]+?(?=[.,;:)]*(?:\s|$))", r"`\g<0>`", what)
    what = re.sub(r"(?<!`)\bAGENTGOV_[A-Z0-9_]+\b(?!`)", r"`\g<0>`", what)
    what = re.sub(r"(?<![`\w])[a-z0-9]+(?:_[a-z0-9]+)+\b(?!`)", variable, what)
    what = re.sub(r"\bdocs/([a-z0-9-]+)\.md", r"[\1](\1.md)", what)
    # Outside code, < and > would read as HTML.
    parts = what.split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "&lt;").replace(">", "&gt;")
    return "`".join(parts).replace("|", "\\|")


def render() -> tuple[str, list[str]]:
    out, undocumented = [BEGIN, ""], []
    names = {
        n.target.id
        for n in ast.walk(ast.parse(CONFIG.read_text()))
        if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)
    }
    for section in sections():
        title = re.sub(r"\s*\(docs/[^)]*\)", "", section.title)
        out += [f"### {title}", ""]
        if section.intro:
            out += [_text(section.intro, names), ""]
        out += ["| Variable | Default | What it does |", "|---|---|---|"]
        for group in section.groups:
            if not group.what:
                undocumented += group.names
            what = _text(group.what, names)
            out.append(f"| {'<br>'.join(group.names)} | {'<br>'.join(group.defaults)} | {what} |")
        out.append("")
    out.append(END)
    return "\n".join(out), undocumented


def main() -> int:
    reference, undocumented = render()
    if undocumented:
        print(f"settings without a comment in src/agentgov/config.py: {', '.join(undocumented)}")
        return 1
    doc = DOC.read_text()
    start, stop = doc.find(BEGIN), doc.find(END)
    if start < 0 or stop < 0:
        print("docs/configuration.md has no settings reference markers")
        return 1
    updated = doc[:start] + reference + doc[stop + len(END) :]
    if "--check" in sys.argv[1:]:
        if updated != doc:
            print("docs/configuration.md is out of date: run scripts/settings-doc.py")
            return 1
        return 0
    DOC.write_text(updated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
